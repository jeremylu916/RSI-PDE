"""Write docs/benchmark-problems.tex: every benchmark equation, its conditions, exact solution, and forcing.

Generated from the task generators so parameters match the code. Reserved (sealed) cases are counted
but their parameters are omitted. Usage (after sourcing scripts/env.sh):
    python scripts/write_problem_latex.py
"""

import math

from pde_rsi.storage import PROJECT_ROOT
from pde_rsi.tasks import FINE_GRID, make_group_pilot, make_pilot, make_wave_pilot, wave_frequency

SPLIT = {"evolution": "train", "development": "validation", "sealed": "reserved"}


def n(value):
    """Compact number for tables."""
    if abs(value-math.pi) < 1e-12:
        return r"$\pi$"
    return f"{value:.4g}"


def case_id(task):
    return r"\texttt{" + task.task_id.replace("_", r"\_") + "}"


def table(tasks, columns):
    """columns: list of (header, function(task) -> str)."""
    public = [t for t in tasks if t.split != "sealed"]
    sealed = sum(t.split == "sealed" for t in tasks)
    spec = "ll" + "r"*len(columns)
    lines = [r"\begin{center}\small", rf"\begin{{tabular}}{{{spec}}}", r"\toprule",
             "Case & Split & " + " & ".join(h for h, _ in columns) + r" \\", r"\midrule"]
    for task in public:
        lines.append(f"{case_id(task)} & {SPLIT[task.split]} & " + " & ".join(f(task) for _, f in columns) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{center}",
              rf"\noindent Reserved cases: {sealed} (parameters kept evaluator-only).", ""]
    return lines


def one_d_columns(family):
    columns = [("$L$", lambda t: n(t.length))]
    if family != "poisson":
        columns.append(("$T$", lambda t: n(t.final_time)))
    columns.append(("$D$", lambda t: n(t.diffusivity)))
    if family == "convection_diffusion":
        columns.append(("$v$", lambda t: n(t.velocity)))
    columns.append(("$A$", lambda t: n(t.amplitude)))
    if family != "poisson":
        columns.append((r"$\beta$", lambda t: n(t.beta)))
    if family == "caputo":
        columns.append((r"$\alpha$", lambda t: n(t.orders[0])))
    if family == "multi_term":
        columns.append((r"$(\alpha_1,\alpha_2)$", lambda t: f"({n(t.orders[0])}, {n(t.orders[1])})"))
        columns.append((r"$(w_1,w_2)$", lambda t: f"({n(t.weights[0])}, {n(t.weights[1])})"))
    columns.append(("Profile", lambda t: {"sine": "sine", "polynomial": "quadratic", "mixed_sine": "mixed"}[t.profile]))
    return columns


PREAMBLE = r"""\documentclass[11pt]{article}
\usepackage[margin=1in]{geometry}
\usepackage{amsmath,amssymb,booktabs}
\newcommand{\Caputo}[1]{{}^{C}_{0}D_t^{#1}}
\begin{document}
\section*{PDE-RSI benchmark problems}

Generated by \texttt{scripts/write\_problem\_latex.py} from \texttt{src/pde\_rsi/tasks.py}. Every problem has a
manufactured exact solution $u$; the forcing $f$ is obtained by substituting $u$ into the equation.
Agents never see $u$, the profile parameters ($A$, $\beta$ or $p$, the spatial profile), or the closed form
of $f$; solver programs receive $f$ and the initial data only as black-box functions.

\paragraph{Caputo derivatives.} For $0<\alpha<1$, with history from $t=0$,
\begin{equation*}
\Caputo{\alpha}u(x,t) = \frac{1}{\Gamma(1-\alpha)}\int_0^t (t-s)^{-\alpha}\,\partial_s u(x,s)\,ds,
\qquad \Caputo{\alpha} t^{p} = \frac{\Gamma(p+1)}{\Gamma(p+1-\alpha)}\,t^{p-\alpha}.
\end{equation*}
A variable order $\alpha(t)$ or $\alpha(x,t)$ is evaluated at the current point:
$\Caputo{\alpha(x,t)}u = \frac{1}{\Gamma(1-\alpha(x,t))}\int_0^t (t-s)^{-\alpha(x,t)}\partial_s u(x,s)\,ds$.

\paragraph{Evaluation.} A case passes when the space--time and final-time relative $L^2$ errors are both at most
$2\times10^{-3}$, the initial and boundary errors are at most $10^{-10}$, and the solve fits in 15\,s and 1\,GB.
Errors use linear interpolation onto uniform nodes and the trapezoidal rule:
""" + rf"""${FINE_GRID['space']}\times{FINE_GRID['time']}$ for 1D families (Poisson: {FINE_GRID['space']} points; FODE:
{FINE_GRID['time']} times) and ${FINE_GRID['wave_space']}\times{FINE_GRID['wave_space']}\times{FINE_GRID['wave_time']}$
for the 2D wave equation.
"""


def sections():
    """The document body (without preamble and end), reused by scripts/write_benchmarks_latex.py."""
    one_d, wave, group = make_pilot(), make_wave_pilot(), make_group_pilot()
    out = [r"""
\section{One-dimensional benchmark (48 public, 24 reserved cases)}
All cases use $x\in[0,L]$, $u(0,t)=u(L,t)=0$ and the exact solution
\begin{equation*}
u(x,t) = A\,s(x)\,\bigl(1+t^{\beta}\bigr) \quad (\text{Poisson: } u(x)=A\,s(x)), \qquad u(x,0)=A\,s(x),
\end{equation*}
with the spatial profile fixed by the split:
\begin{equation*}
s(x)=\begin{cases}
\sin(\pi x/L) & \text{train,}\\
4\,\dfrac{x}{L}\Bigl(1-\dfrac{x}{L}\Bigr) & \text{validation,}\\
\sin(\pi x/L)+\tfrac14\sin(3\pi x/L) & \text{reserved.}
\end{cases}
\end{equation*}
Write $g(t)=1+t^{\beta}$.
"""]
    equations = {
        "poisson": (r"Poisson", r"-D\,u_{xx} = f(x),\quad x\in(0,L)",
                    r"f = -D\,A\,s''(x)"),
        "heat": (r"Heat", r"u_t - D\,u_{xx} = f(x,t),\quad x\in(0,L),\ t\in(0,T]",
                 r"f = A\bigl[\beta t^{\beta-1}s(x) - D\,g(t)\,s''(x)\bigr]"),
        "convection_diffusion": (r"Convection--diffusion", r"u_t + v\,u_x - D\,u_{xx} = f(x,t)",
                                 r"f = A\bigl[\beta t^{\beta-1}s - D\,g\,s'' + v\,g\,s'\bigr]"),
        "burgers": (r"Viscous Burgers", r"u_t + u\,u_x - D\,u_{xx} = f(x,t)",
                    r"f = A\bigl[\beta t^{\beta-1}s - D\,g\,s''\bigr] + A^2 g^2\,s\,s'"),
        "caputo": (r"Caputo subdiffusion", r"\Caputo{\alpha}u - D\,u_{xx} = f(x,t),\quad 0<\alpha<1",
                   r"f = A\Bigl[\frac{\Gamma(\beta+1)}{\Gamma(\beta+1-\alpha)}t^{\beta-\alpha}s - D\,g\,s''\Bigr]"),
        "multi_term": (r"Multi-term Caputo diffusion",
                       r"\sum_{j=1}^{2} w_j\,\Caputo{\alpha_j}u - D\,u_{xx} = f(x,t)",
                       r"f = A\Bigl[\sum_j w_j\frac{\Gamma(\beta+1)}{\Gamma(\beta+1-\alpha_j)}t^{\beta-\alpha_j}s"
                       r" - D\,g\,s''\Bigr]"),
    }
    for family, (title, equation, forcing) in equations.items():
        out += [rf"\subsection{{{title}}}", r"\begin{align*}", equation + r"\\", forcing, r"\end{align*}"]
        out += table([t for t in one_d if t.family == family], one_d_columns(family))
    omega_note = ", ".join(f"{case_id(t)}: {wave_frequency(t):.4f}" for t in wave if t.split != "sealed")
    out += [r"""
\section{Two-dimensional wave equation (8 public, 4 reserved cases)}
\begin{align*}
&u_{tt} - D\,(u_{xx}+u_{yy}) = f(x,y,t),\qquad (x,y)\in(0,L)^2,\ t\in(0,T],\\
&u = 0 \text{ on } \partial(0,L)^2,\qquad u(x,y,0)=A\,s(x)s(y),\qquad u_t(x,y,0)=0,\\
&u(x,y,t) = A\,s(x)\,s(y)\,\bigl(\cos\omega t + t^{\beta}\bigr),\qquad \omega=\sqrt{D}\,\pi\sqrt{2}/L,\\
&f = A\Bigl[\bigl(-\omega^2\cos\omega t+\beta(\beta-1)t^{\beta-2}\bigr)S
   - D\bigl(\cos\omega t+t^{\beta}\bigr)\Delta S\Bigr],\\
&S(x,y)=s(x)\,s(y),
\end{align*}
with $s$ as in the 1D benchmark (train: sine, $\beta=2.5$; validation: quadratic, $\beta=1.5$, so
$u_{tt}\sim t^{-1/2}$ is singular at $t=0$; reserved: mixed, $\beta=1.25$). $D=c^2$ is the squared wave speed.
""" + rf"\noindent Frequencies $\omega$: {omega_note}." + "\n"]
    out += table(wave, [("$L$", lambda t: n(t.length)), ("$T$", lambda t: n(t.final_time)),
                        ("$D=c^2$", lambda t: n(t.diffusivity)), ("$A$", lambda t: n(t.amplitude)),
                        (r"$\beta$", lambda t: n(t.beta))])
    out += [r"""
\section{Group FPDE examples (16 public, 4 reserved cases)}
All start from rest and use $t\in(0,1]$. The fractional PDEs use $x\in(0,\pi)$ with $u(0,t)=u(\pi,t)=0$ and
$u(x,0)=0$. The exact solutions are $u=t^{p}$ (FODE) and $u=t^{p}\sin x$ (FPDEs). The paper instances are
$p=3$ with order coefficient $0.5$ (so $u=t^3$ or $u=t^3\sin x$); the other cases vary the order and $p$.

\subsection{Fractional ODE}
\begin{equation*}
\Caputo{\alpha}u(t) = f(t),\quad u(0)=0,\qquad u(t)=t^{p},\qquad
f(t)=\frac{\Gamma(p+1)}{\Gamma(p+1-\alpha)}\,t^{p-\alpha}.
\end{equation*}
"""]
    by = lambda fam: [t for t in group if t.family == fam]
    out += table(by("fode"), [(r"$\alpha$", lambda t: n(t.orders[0])), ("$p$", lambda t: n(t.beta))])
    out += [r"""\subsection{Caputo FPDE}
\begin{equation*}
\Caputo{\alpha}u = u_{xx} + f(x,t),\qquad u=t^{p}\sin x,\qquad
f(x,t)=\Bigl[\frac{\Gamma(p+1)}{\Gamma(p+1-\alpha)}\,t^{p-\alpha} + t^{p}\Bigr]\sin x.
\end{equation*}
"""]
    out += table(by("fpde_caputo"), [(r"$\alpha$", lambda t: n(t.orders[0])), ("$p$", lambda t: n(t.beta))])
    out += [r"""\subsection{Time-variable-order FPDE}
\begin{align*}
&\Caputo{\alpha(t)}u = u_{xx} + f(x,t),\qquad \alpha(t)=c\,\sin^2 t,\qquad u=t^{p}\sin x,\\
&f=\Bigl[\frac{\Gamma(p+1)}{\Gamma(p+1-\alpha(t))}\,t^{p-\alpha(t)} + t^{p}\Bigr]\sin x.
\end{align*}
"""]
    out += table(by("fpde_variable_order"), [("$c$", lambda t: n(t.orders[0])), ("$p$", lambda t: n(t.beta))])
    out += [r"""\subsection{Space--time-variable-order FPDE}
\begin{align*}
&\Caputo{\alpha(x,t)}u = u_{xx} + f(x,t),\qquad \alpha(x,t)=c\,t^{2}\sin x,\qquad u=t^{p}\sin x,\\
&f=\Bigl[\frac{\Gamma(p+1)}{\Gamma(p+1-\alpha(x,t))}\,t^{p-\alpha(x,t)} + t^{p}\Bigr]\sin x.
\end{align*}
"""]
    out += table(by("fpde_variable_order_xt"), [("$c$", lambda t: n(t.orders[0])), ("$p$", lambda t: n(t.beta))])
    return out


def main():
    out = [PREAMBLE, *sections(), r"\end{document}"]
    path = PROJECT_ROOT/"docs/benchmark-problems.tex"
    path.write_text("\n".join(out)+"\n")
    print(path)


if __name__ == "__main__":
    main()
