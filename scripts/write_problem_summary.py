"""Write docs/benchmark-problems.md: equations, IC/BC, exact solutions, and public case parameters.

Generated from the task generators so the summary matches the code. Reserved (sealed) cases are
summarized by count only. Usage (after sourcing scripts/env.sh):
    python scripts/write_problem_summary.py
"""

import math
from pathlib import Path

from pde_rsi.storage import PROJECT_ROOT
from pde_rsi.tasks import make_group_pilot, make_pilot, make_wave_pilot, wave_frequency

SPLIT_NAMES = {"evolution": "train", "development": "validation", "sealed": "reserved"}


def g(value):
    return f"{value:.6g}"


def profile(task, z="x"):
    L = g(task.length)
    if task.profile == "polynomial":
        return f"4({z}/{L})(1-{z}/{L})"
    if task.profile == "mixed_sine":
        return f"[sin(pi {z}/{L}) + 0.25 sin(3 pi {z}/{L})]"
    return f"sin(pi {z}/{L})" if task.length != math.pi else f"sin({z})"


def exact(task):
    A = g(task.amplitude)
    if task.family == "poisson":
        return f"{A} · {profile(task)}"
    if task.family == "wave2d":
        return f"{A} · {profile(task)} · {profile(task, 'y')} · (cos({g(wave_frequency(task))} t) + t^{g(task.beta)})"
    if task.family == "fode":
        return f"t^{g(task.beta)}"
    if task.family.startswith("fpde_"):
        return f"t^{g(task.beta)} · sin(x)"
    return f"{A} · {profile(task)} · (1 + t^{g(task.beta)})"


def order_text(task):
    if not task.orders:
        return "—"
    c = g(task.orders[0])
    if task.family == "fpde_variable_order":
        return f"alpha(t) = {c} sin^2 t"
    if task.family == "fpde_variable_order_xt":
        return f"alpha(x,t) = {c} sin(x) t^2"
    if task.family == "multi_term":
        return f"alpha = ({', '.join(g(a) for a in task.orders)}), weights ({', '.join(g(w) for w in task.weights)})"
    return f"alpha = {c}"


FAMILY_TEXT = {
    "poisson": ("-D u_xx = f(x)", "x in [0, L]", "u(0) = u(L) = 0", "none (stationary)"),
    "heat": ("u_t - D u_xx = f(x, t)", "x in [0, L], t in [0, T]", "u(0,t) = u(L,t) = 0", "u(x,0) = A s(x)"),
    "convection_diffusion": ("u_t + v u_x - D u_xx = f(x, t)", "x in [0, L], t in [0, T]",
                             "u(0,t) = u(L,t) = 0", "u(x,0) = A s(x)"),
    "burgers": ("u_t + u u_x - D u_xx = f(x, t)", "x in [0, L], t in [0, T]", "u(0,t) = u(L,t) = 0",
                "u(x,0) = A s(x)"),
    "caputo": ("D_t^alpha u - D u_xx = f(x, t), alpha in (0,1)", "x in [0, L], t in [0, T]",
               "u(0,t) = u(L,t) = 0", "u(x,0) = A s(x)"),
    "multi_term": ("sum_j w_j D_t^alpha_j u - D u_xx = f(x, t)", "x in [0, L], t in [0, T]",
                   "u(0,t) = u(L,t) = 0", "u(x,0) = A s(x)"),
    "wave2d": ("u_tt - D (u_xx + u_yy) = f(x, y, t)", "(x, y) in [0, L]^2, t in [0, T]",
               "u = 0 on all four edges", "u(x,y,0) = A s(x) s(y), u_t(x,y,0) = 0"),
    "fode": ("D_t^alpha u(t) = f(t)", "t in [0, 1]", "none", "u(0) = 0"),
    "fpde_caputo": ("D_t^alpha u = u_xx + f(x, t)", "x in [0, pi], t in [0, 1]", "u(0,t) = u(pi,t) = 0",
                    "u(x,0) = 0"),
    "fpde_variable_order": ("D_t^{alpha(t)} u = u_xx + f(x, t), alpha(t) = c sin^2 t", "x in [0, pi], t in [0, 1]",
                            "u(0,t) = u(pi,t) = 0", "u(x,0) = 0"),
    "fpde_variable_order_xt": ("D_t^{alpha(x,t)} u = u_xx + f(x, t), alpha(x,t) = c sin(x) t^2",
                               "x in [0, pi], t in [0, 1]", "u(0,t) = u(pi,t) = 0", "u(x,0) = 0"),
}


def family_section(family, tasks):
    equation, domain, boundary, initial = FAMILY_TEXT[family]
    public = [t for t in tasks if t.split != "sealed"]
    sealed = [t for t in tasks if t.split == "sealed"]
    lines = [f"### `{family}`", "", f"- Equation: `{equation}`", f"- Domain: {domain}",
             f"- Boundary conditions: {boundary}", f"- Initial conditions: {initial}"]
    lines.append("")
    header = "| Case | Split | L | T | D | " + ("v | " if family == "convection_diffusion" else "") + \
             "Order | Exact solution u |"
    lines += [header, "| " + " | ".join(["---"]*(header.count("|")-1)) + " |"]
    for task in public:
        cells = [f"`{task.task_id}`", SPLIT_NAMES[task.split], g(task.length),
                 "—" if family == "poisson" else g(task.final_time), g(task.diffusivity)]
        if family == "convection_diffusion":
            cells.append(g(task.velocity))
        cells += [order_text(task), f"`{exact(task)}`"]
        lines.append("| " + " | ".join(cells) + " |")
    profiles = sorted({t.profile for t in sealed})
    lines += ["", f"Reserved cases: {len(sealed)} (profile: {', '.join(profiles)}). Parameters stay evaluator-only.", ""]
    return lines


def main():
    one_d, wave, group = make_pilot(), make_wave_pilot(), make_group_pilot()
    lines = [
        "# Benchmark problems: equations, conditions, and exact solutions", "",
        "Generated by `scripts/write_problem_summary.py` from the task generators in `src/pde_rsi/tasks.py`.",
        "Rerun it after any benchmark change. All problems use manufactured exact solutions. The forcing f",
        "is computed by inserting the exact solution into the equation (public code: `equations.py`,",
        "`equations2d.py`, `equations_group.py`; evaluator-only exact solutions: `reference.py`).", "",
        "## Common evaluation rules", "",
        "- A case passes when the combined space-time relative L2 and the final-time relative L2 are both",
        "  at most 0.002, the initial and boundary errors are at most 1e-10, and the solve fits in 15 s and",
        "  1,024 MB.",
        "- Errors are measured after linear interpolation onto uniform evaluator nodes, using trapezoidal",
        "  integration: 512 x-points x 500 times for 1D families (Poisson: 512 points; FODE: 500 times) and",
        "  128 x 128 x 100 for the wave (evaluator v5; earlier runs used 65 x 17).",
        "- Agents never see the exact solutions, the profile parameters (profile, amplitude A, mode, power",
        "  beta/p), or the closed-form forcing. Programs receive f and the initial data only as callables.",
        "",
        "## 1D benchmark: 48 public and 24 reserved cases (`benchmarks/`, published on Hugging Face)", "",
        "Exact solution `u(x,t) = A s(x) (1 + t^beta)`; Poisson uses `u(x) = A s(x)`. The spatial profile",
        "s(x) is fixed by the split: train uses `sin(pi x/L)`, validation uses `4(x/L)(1-x/L)` (a quadratic,",
        "which a second-order finite-difference solver reproduces exactly at its grid nodes), and reserved",
        "cases use `sin(pi x/L) + 0.25 sin(3 pi x/L)`. Variants v0-v3 increase D, the velocity, A, the",
        "fractional orders, and (from v2 on) T.", "",
    ]
    for family in ("poisson", "heat", "convection_diffusion", "burgers", "caputo", "multi_term"):
        lines += family_section(family, [t for t in one_d if t.family == family])
    lines += ["## 2D wave: 8 public and 4 reserved cases (`benchmarks/wave2d/`)", "",
              "`u = A s(x) s(y) (cos(omega t) + t^beta)` with `omega = sqrt(D) pi sqrt(2) / L` (the fundamental-mode",
              "frequency). Validation uses beta = 1.5, so `u_tt ~ t^(-1/2)` and the forcing is singular at t = 0.", ""]
    lines += family_section("wave2d", wave)
    lines += ["## Group FPDE examples: 16 public and 4 reserved cases (`benchmarks/group_fpde/`, group-fpde-v2)", "",
              "`u = t^p sin(x)`, or `u = t^p` for the FODE. The paper instances (order coefficient 0.5, p = 3,",
              "so u = t^3 sin x) are the first validation case of each family. The other cases vary the order",
              "and the power p. Forcing: `f = Gamma(p+1)/Gamma(p+1-alpha) t^(p-alpha) sin x + t^p sin x`, with alpha",
              "evaluated at the current point; a variable order is frozen at (x, t) inside the Caputo integral.", ""]
    for family in ("fode", "fpde_caputo", "fpde_variable_order", "fpde_variable_order_xt"):
        lines += family_section(family, [t for t in group if t.family == family])
    path = PROJECT_ROOT/"docs/benchmark-problems.md"
    path.write_text("\n".join(lines)+"\n")
    print(path)


if __name__ == "__main__":
    main()
