"""Export one public task as a self-contained folder: inputs, exact solution, and final agent outputs.

Usage (after sourcing scripts/env.sh):
    python scripts/export_task_example.py burgers-g1-v0 --runs runs/code-agents-fine-1d-*-20261016

Layout of tasks/<task_id>/:
    input_agent_view.json  what the model and the solver program are told (no closed-form data)
    problem_full.json      full benchmark record, including the forcing expression and profile parameters
    problem.tex            the equation, conditions, and exact solution with this case's numbers
    reference.npz          exact solution on the evaluator grid (x, t, u)
    outputs/<model>-<start>/<arm>/
        solution.npz       the final agent's returned solution (as saved by the run)
        solver.py          the final program for this task's family
        metrics.json       evaluator result for this task (fine grid)
    README.md              summary table of every output
The exact solution is for inspection only; it is never given to agents.
"""

import argparse
import json
import shutil
from pathlib import Path

import numpy as np

from pde_rsi.codegen import agent_problem_record
from pde_rsi.experiment import selected_tasks
from pde_rsi.reference import output_nodes, reference
from pde_rsi.storage import PROJECT_ROOT, project_path

MODELS = {"us.anthropic.claude-sonnet-4-5-20250929-v1:0": "sonnet45", "openai.gpt-oss-120b-1:0": "gpt-oss",
          "us.openai.gpt-5.5": "gpt55", "us.openai.gpt-6.1-sol": "gpt61", "us.anthropic.claude-opus-5-5": "opus55"}
LABELS = {"sonnet45": "Claude Sonnet 4.5", "gpt-oss": "GPT-OSS-120B", "gpt55": "GPT-5.5", "gpt61": "GPT-6.1",
          "opus55": "Claude Opus 5.5"}
PROFILES = {"sine": r"\sin(\pi x/{L})", "polynomial": r"4\,\frac{{x}}{{{L}}}\Bigl(1-\frac{{x}}{{{L}}}\Bigr)",
            "mixed_sine": r"\sin(\pi x/{L})+\tfrac14\sin(3\pi x/{L})"}


def write_json(path, value):
    path.write_text(json.dumps(value, indent=2, sort_keys=True, allow_nan=False)+"\n")


def problem_tex(task):
    profile = PROFILES[task.profile].format(L=f"{task.length:g}")
    return "\n".join([
        rf"% {task.task_id} ({task.split}); generated by scripts/export_task_example.py",
        r"\begin{align*}",
        r"&u_t + u\,u_x - D\,u_{xx} = f(x,t), \qquad x\in(0,L),\ t\in(0,T],\\",
        r"&u(0,t)=u(L,t)=0,\qquad u(x,0)=A\,s(x),\\",
        rf"&L={task.length:g},\quad T={task.final_time:g},\quad D={task.diffusivity:g},\quad A={task.amplitude:g},"
        rf"\quad \beta={task.beta:g},\qquad s(x)={profile},\\",
        rf"&u(x,t) = A\,s(x)\,\bigl(1+t^{{\beta}}\bigr),\\",
        r"&f = A\bigl[\beta t^{\beta-1}s - D\,(1+t^{\beta})\,s''\bigr] + A^2(1+t^{\beta})^2\,s\,s'.",
        r"\end{align*}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("task_id")
    parser.add_argument("--runs", type=Path, nargs="+", required=True)
    parser.add_argument("--output", type=Path, default=PROJECT_ROOT/"tasks")
    args = parser.parse_args()
    tasks = {t.task_id: t for split in ("evolution", "development") for t in selected_tasks(PROJECT_ROOT, split)}
    task = tasks[args.task_id]
    folder = project_path(args.output/task.task_id)
    folder.mkdir(parents=True, exist_ok=False)
    write_json(folder/"input_agent_view.json", agent_problem_record(task))
    write_json(folder/"problem_full.json", task.public_record())
    (folder/"problem.tex").write_text(problem_tex(task))
    x, t = output_nodes(task)
    np.savez_compressed(folder/"reference.npz", x=x, t=t, u=reference(task, x, t))
    rows = []
    for run in sorted(map(project_path, args.runs)):
        manifest = json.loads((run/"manifest.json").read_text())
        if task.task_id not in manifest["task_ids"][task.split]:
            continue
        name = f"{MODELS[manifest['model_config']['model']]}-{manifest['start']}"
        for arm in ("single", "rsi"):
            result = next(r for r in json.loads((run/arm/"frozen_results.json").read_text())
                          if r["task_id"] == task.task_id)
            target = folder/"outputs"/name/arm
            target.mkdir(parents=True)
            solution = run/arm/"solutions"/f"{task.task_id}.npz"
            if solution.exists():
                shutil.copyfile(solution, target/"solution.npz")
            shutil.copyfile(run/arm/"programs/frozen"/f"{task.family}.py", target/"solver.py")
            write_json(target/"metrics.json", {**result, "source_run": str(run.relative_to(PROJECT_ROOT)),
                                               "evaluator_version": manifest["evaluator_version"]})
            rows.append((LABELS[name.split("-")[0] if not name.startswith("gpt-oss") else "gpt-oss"],
                         manifest["start"], arm, result))
    lines = [f"# Task `{task.task_id}`", "",
             f"Viscous Burgers, {task.split} split (`g1` = validation, quadratic profile). Exact solution:",
             f"`u(x,t) = {task.amplitude:g} · 4(x/{task.length:g})(1 - x/{task.length:g}) · (1 + t^{task.beta:g})` on "
             f"x ∈ [0, {task.length:g}], t ∈ [0, {task.final_time:g}], D = {task.diffusivity:g}.", "",
             "See the module docstring of `scripts/export_task_example.py` for the file layout. `reference.npz` holds",
             f"the exact solution on the evaluator grid ({len(x)} x-points × {len(t)} times); it is for inspection only",
             "and was never given to agents.", "",
             "Final outputs of each comparison run (fine evaluation grid, evaluator v5):", "",
             "| Model | Start | Arm | Relative L2 | Final-time rel. L2 | Passed | Returned grid (nx × nt) | Solve time (s) |",
             "| --- | --- | --- | ---: | ---: | :---: | ---: | ---: |"]
    for label, start, arm, r in rows:
        ok = r["status"] == "ok"
        lines.append(f"| {label} | {start} | {'single run' if arm == 'single' else 'RSI'} | "
                     f"{r['relative_l2']:.2e} | {r['final_relative_l2']:.2e} | {'yes' if r['passed'] else 'no'} | "
                     + (f"{r.get('nx')} × {r.get('nt')}" if ok else r["status"]) + f" | {r['wall_seconds']:.2f} |")
    (folder/"README.md").write_text("\n".join(lines)+"\n")
    print(folder)


if __name__ == "__main__":
    main()
